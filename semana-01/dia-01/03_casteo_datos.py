# Casteo
# Es convertir un dato en otro tipo de dato
# El int => indica que el dato se va a convertir en un entero
print( int("100") )

# El str => indica que se va a convertir en string un dato
print( str(200) )

# El float => indica que se va a convertir a flotante un dato
print( float("3.141516"))

print(float("3.141516") + 10)

# El round => redondear un número al entero mas cercano
print(round(3.50))